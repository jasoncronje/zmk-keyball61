def c_name(key):
    return {'%': 'percent', '-': 'dash', ' ': 'space'}.get(key, key)


def glyph(name, rows, static=False):
    width = max(len(r) for r in rows)
    words = ', '.join(f"0x{int(r.ljust(width, '.').replace('.', '0').replace('#', '1'), 2):x}"
                      for r in rows)
    return (f"static const uint32_t {name}_rows[] = {{{words}}};\n"
            f"{'static ' if static else ''}const struct glyph {name} = {{.w = {width}, .h = {len(rows)}, .rows = {name}_rows}};\n")


def main():
    out = ["// Generated by scripts/gen_glyphs.py; edit the tables there, not this file\n",
           '#include "glyphs.h"\n']

    for key, rows in SMALL.items():
        out.append(glyph(f"small_{c_name(key)}", rows, static=True))
    out.append("const struct glyph *const small_font[96] = {")
    for key in SMALL:
        out.append(f"    ['{key}' - ' '] = &small_{c_name(key)},")
    out.append("};\n")

    for key, rows in BIG.items():
        out.append(glyph(f"big_{key}", rows, static=True))
    out.append("const struct glyph *const big_digits[10] = {")
    out.append("    " + ", ".join(f"&big_{key}" for key in BIG) + ",")
    out.append("};\n")

    for key, rows in ICONS.items():
        out.append(glyph(f"icon_{key}", rows))
    out.append(glyph("icon_fingerprint_on", FP_ON))
    out.append(glyph("icon_fingerprint_off", FP_OFF))

    path = Path(__file__).resolve().parent.parent / 'src' / 'glyphs.c'
    path.write_text('\n'.join(out))


if __name__ == '__main__':
    main()
